/* build-bundles.mjs
   Makes the site work when the HTML files are opened by double-clicking (file://), where browsers block ES modules and fetch().
   It writes js/bundles/<page>.js (classic scripts) and js/bundles/data.js (all JSON data in one file).
   Run after editing any file in js/ or data/:   npm run bundle
   Every page loads its bundle with a plain <script defer> tag in the head, so it works the same on a host, a local server and a double-click. */
import { build } from 'esbuild';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/\/$/, '');
const pagesDir = join(root, 'js/pages');
const out = join(root, 'js/bundles');
mkdirSync(out, { recursive: true });

// 1. each page -> one classic script. Pages use top-level await, so the body is wrapped in an async function.
for (const f of readdirSync(pagesDir).filter((x) => x.endsWith('.js') && !x.startsWith('__') && x !== '404.js')) {
  const src = readFileSync(join(pagesDir, f), 'utf8').split('\n');
  const imports = src.filter((l) => /^import\s/.test(l));
  const body = src.filter((l) => !/^import\s/.test(l));
  const entry = join(pagesDir, `__entry_${f}`);
  writeFileSync(entry, `${imports.join('\n')}\n(async () => {\n${body.join('\n')}\n})();\n`);
  try {
    await build({ entryPoints: [entry], bundle: true, format: 'iife', target: 'es2020', outfile: join(out, f), minify: true, logLevel: 'error' });
  } finally { rmSync(entry, { force: true }); }
}

// 2. all JSON data + translations in one file
const files = {};
const walk = (dir) => { for (const n of readdirSync(dir)) { const p = join(dir, n); if (statSync(p).isDirectory()) walk(p); else if (n.endsWith('.json')) files[p.slice(root.length + 1)] = JSON.parse(readFileSync(p, 'utf8')); } };
walk(join(root, 'data'));
writeFileSync(join(out, 'data.js'), `/* generated by tools/build-bundles.mjs - do not edit */\nwindow.__BBC_FILES = ${JSON.stringify(files)};\n`);
console.log('bundled', readdirSync(out).length, 'files');

// 3. bake the English text into every HTML file so the first paint is never empty
//    (the page scripts still run afterwards and keep everything in sync)
const flat = (o, p = '', out = {}) => { for (const [k, v] of Object.entries(o)) { const key = p ? `${p}.${k}` : k; if (v && typeof v === 'object') flat(v, key, out); else out[key] = v; } return out; };
const dict = {};
for (const [path, json] of Object.entries(files)) if (/^data\/i18n\/(en|pages\/[\w-]+\.en)\.json$/.test(path)) Object.assign(dict, flat(json));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
const htmlFiles = [];
const walkHtml = (dir) => { for (const n of readdirSync(dir)) { if (n === 'node_modules' || n === 'js' || n === 'data' || n === 'assets') continue; const p = join(dir, n); if (statSync(p).isDirectory()) walkHtml(p); else if (n.endsWith('.html')) htmlFiles.push(p); } };
walkHtml(root);
let baked = 0, missing = new Set();
for (const file of htmlFiles) {
  let s = readFileSync(file, 'utf8'); const before = s;
  // leaf elements: <tag ... data-i18n="key" ...>text-or-empty</tag>
  s = s.replace(/<(\w+)([^>]*?\sdata-i18n="([^"]+)"[^>]*)>([^<]*)<\/\1>/g, (m, tag, attrs, key) => { if (dict[key] == null) { missing.add(key); return m; } baked++; return `<${tag}${attrs}>${esc(dict[key]).replace(/\{\w+\}/g, (x) => x)}</${tag}>`; });
  const setAttr = (name, dataAttr) => {
    s = s.replace(new RegExp(`<(\\w+)([^>]*?\\s${dataAttr}="([^"]+)"[^>]*)>`, 'g'), (m, tag, attrs, key) => {
      if (dict[key] == null) { missing.add(key); return m; }
      const clean = attrs.replace(new RegExp(`\\s${name}="[^"]*"`), '');
      return `<${tag}${clean} ${name}="${esc(dict[key])}">`;
    });
  };
  setAttr('placeholder', 'data-i18n-placeholder'); setAttr('aria-label', 'data-i18n-aria'); setAttr('title', 'data-i18n-title');
  if (s !== before) writeFileSync(file, s);
}
console.log('baked', baked, 'texts into', htmlFiles.length, 'html files', missing.size ? '| missing keys: ' + [...missing].slice(0, 8).join(', ') : '');

// 4. one stylesheet per page: the page's own <link> list is remembered in data-src, merged + minified into css/bundles/<name>.css
//    (fewer requests = faster first paint). Source files in css/ stay the place you edit.
import { transform } from 'esbuild';
mkdirSync(join(root, 'css/bundles'), { recursive: true });
let cssPages = 0;
for (const file of htmlFiles) {
  let s = readFileSync(file, 'utf8'); const before = s;
  const rel = file.slice(root.length + 1); const depth = rel.split('/').length - 1; const up = '../'.repeat(depth);
  const name = rel.replace(/\.html$/, '').replace(/\//g, '-');
  // already bundled?  then take the list from data-src, otherwise from the plain links
  let list = null; const m = s.match(/<link rel="stylesheet" href="[^"]*css\/bundles\/[^"]*"[^>]*data-src="([^"]+)"[^>]*>/);
  if (m) list = m[1].split(',');
  else { const links = [...s.matchAll(/<link rel="stylesheet" href="((?:\.\.\/)*css\/([^"]+)\.css)">\s*/g)]; if (links.length) list = links.map((x) => x[2]); }
  if (!list) continue;
  let css = '';
  for (const n of list) css += readFileSync(join(root, 'css', n + '.css'), 'utf8').replace(/url\("\.\.\/assets\//g, 'url("../../assets/') + '\n';
  const min = (await transform(css, { loader: 'css', minify: true })).code;
  writeFileSync(join(root, 'css/bundles', name + '.css'), min);
  const tag = `<link rel="stylesheet" href="${up}css/bundles/${name}.css" data-src="${list.join(',')}">`;
  if (m) s = s.replace(/<link rel="stylesheet" href="[^"]*css\/bundles\/[^"]*"[^>]*data-src="[^"]+"[^>]*>/, tag);
  else { let first = true; s = s.replace(/<link rel="stylesheet" href="(?:\.\.\/)*css\/[^"]+\.css">\s*/g, () => { if (first) { first = false; return tag + '\n  '; } return ''; }); }
  if (s !== before) writeFileSync(file, s);
  cssPages++;
}
console.log('css bundles for', cssPages, 'pages');
